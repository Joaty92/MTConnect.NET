"""Profile YAML + MTConnect device.xml emitters.

Mirrors the structure produced by the CLI tool at C:\\Tools\\OPCUAProfilexml so the
output is a drop-in replacement: the YAML loaded by MTConnect.NET-AgentModule-OpcUaAdapter
and the device.xml whose Device id/uuid/name get rewritten to the configured deviceKey
at module startup.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime
from typing import Iterable
from xml.etree import ElementTree as ET


@dataclass
class SelectedVariable:
    """One ticked Variable plus the metadata the YAML/XML emitters need."""

    node_id: str                  # full OPC UA NodeId string, e.g. ns=3;s="DB"."Field"
    browse_name: str              # display name from the server
    parent_browse_name: str       # parent Object's BrowseName (used for component grouping)
    data_type_name: str           # OPC UA DataType, used to infer numeric vs. other
    kind: str = "event"           # "sample" or "event"
    data_item_key: str = ""       # MTConnect DataItem id; auto-suggested from browse_name
    mtconnect_type: str = ""      # MTConnect type vocabulary, e.g. "PATH_FEEDRATE_OVERRIDE"
    mtconnect_units: str = ""     # MTConnect units, e.g. "MILLIMETER" / "PERCENT"
    mtconnect_subtype: str = ""   # optional MTConnect subType, e.g. "ACTUAL" / "COMMANDED"


def slugify(text: str, *, keep_underscores: bool = False) -> str:
    """Lowercase, replace non-alphanumeric runs with single underscores."""
    if not text:
        return "untitled"
    pattern = r"[^a-z0-9_]+" if keep_underscores else r"[^a-z0-9]+"
    s = re.sub(pattern, "_", text.lower()).strip("_")
    return s or "untitled"


def infer_kind(data_type_name: str) -> str:
    """Guess MTConnect category from the OPC UA DataType — numeric → sample, else event.
    Note: CONDITION is never inferred from data type alone; the user picks it explicitly
    when mapping a fault/alarm-state node."""
    dt = (data_type_name or "").lower()
    numeric_markers = ("double", "float", "int", "uint", "number", "decimal", "real")
    return "sample" if any(m in dt for m in numeric_markers) else "event"


def kind_to_category(kind: str) -> str:
    """Map UI kind string to MTConnect category attribute value."""
    k = (kind or "").lower()
    if k == "sample":
        return "SAMPLE"
    if k == "condition":
        return "CONDITION"
    return "EVENT"


def suggest_data_item_key(browse_name: str) -> str:
    """Slug of the BrowseName, suitable for use as a DataItem id."""
    return slugify(browse_name)


def build_profile_yaml(
    selections: Iterable[SelectedVariable],
    endpoint_url: str,
    root_node_id: str,
) -> str:
    """Render the mappings YAML grouped by parent BrowseName."""
    selections = list(selections)
    lines: list[str] = []
    lines.append(f"# Generated by OPCUAProfilexmlGUI on {datetime.now():%Y-%m-%d %H:%M}")
    lines.append(f"# Source: {endpoint_url}")
    lines.append(f"# Root:   {root_node_id}")
    lines.append("")
    lines.append("mappings:")

    groups: dict[str, list[SelectedVariable]] = {}
    for sel in selections:
        groups.setdefault(sel.parent_browse_name or "(root)", []).append(sel)

    for parent, items in groups.items():
        lines.append(f"  # ---- {parent} ----")
        for s in items:
            escaped = s.node_id.replace("'", "''")
            lines.append(f"  - nodeId: '{escaped}'")
            lines.append(f"    dataItemKey: {s.data_item_key}")
            lines.append(f"    kind: {s.kind}")
            # Spec-aware fields are informational only: the OpcUaAdapter module reads
            # just nodeId/dataItemKey/kind, and the authoritative type/units/subType
            # live in the generated device.xml. Emit as comments so nobody edits a
            # YAML key that the agent silently ignores.
            if s.mtconnect_type:
                lines.append(f"    # type: {s.mtconnect_type} (see device.xml — authoritative)")
            if s.mtconnect_units:
                lines.append(f"    # units: {s.mtconnect_units} (see device.xml — authoritative)")
            if s.mtconnect_subtype:
                lines.append(f"    # subType: {s.mtconnect_subtype} (see device.xml — authoritative)")
        lines.append("")
    return "\n".join(lines)


def build_device_xml(selections: Iterable[SelectedVariable], profile_name: str) -> str:
    """Render the MTConnect device.xml grouped by parent Object → Component.

    The Device id/uuid/name are placeholders; MTConnect.NET-AgentModule-OpcUaAdapter
    rewrites them to the configured deviceKey at startup.
    """
    selections = list(selections)
    device = ET.Element(
        "Device",
        attrib={"id": "placeholder", "name": "placeholder", "uuid": "placeholder"},
    )
    description = ET.SubElement(
        device,
        "Description",
        attrib={"manufacturer": "OPC UA"},
    )
    description.text = f"Auto-generated from profile '{profile_name}'"

    data_items = ET.SubElement(device, "DataItems")
    ET.SubElement(
        data_items,
        "DataItem",
        attrib={"category": "EVENT", "id": "avail", "type": "AVAILABILITY"},
    )

    components = ET.SubElement(device, "Components")
    used_ids: set[str] = set()
    groups: dict[str, list[SelectedVariable]] = {}
    for sel in selections:
        groups.setdefault(sel.parent_browse_name or "root", []).append(sel)

    for parent, items in groups.items():
        component_id = slugify(parent)
        unique_id = component_id
        n = 1
        while unique_id in used_ids:
            n += 1
            unique_id = f"{component_id}_{n}"
        used_ids.add(unique_id)

        component = ET.SubElement(
            components,
            "Component",
            attrib={"id": unique_id, "name": parent},
        )
        component_items = ET.SubElement(component, "DataItems")
        for s in items:
            # Set both id and name to dataItemKey at generation time. The
            # OpcUaAdapter module rewrites id to "{deviceKey}_{name}" when it
            # AddDevice's the template, giving each deployed instance a
            # globally-unique id while keeping name stable for observation
            # routing (the agent's AddObservation resolves by Name OR ID OR
            # Source, so the YAML's dataItemKey continues to match against the
            # un-prefixed name).
            attrib = {
                "category": kind_to_category(s.kind),
                "id": s.data_item_key,
                "name": s.data_item_key,
                "type": s.mtconnect_type or "VARIABLE",
            }
            if s.mtconnect_subtype:
                attrib["subType"] = s.mtconnect_subtype
            if s.mtconnect_units:
                attrib["units"] = s.mtconnect_units
            ET.SubElement(component_items, "DataItem", attrib=attrib)

    ET.indent(device, space="  ")
    body = ET.tostring(device, encoding="unicode")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"<!-- Generated by OPCUAProfilexmlGUI on {datetime.now():%Y-%m-%d %H:%M}. "
        "Device id/uuid/name are rewritten to deviceKey by the OpcUaAdapter module at startup. -->\n"
        f"{body}\n"
    )
